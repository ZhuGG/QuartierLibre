export const normalize = (s) =>
  s
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
export function filterPlaces(
  list,
  {
    mode,
    category = "Tout",
    district = "Tout le 7e",
    query = "",
    favorites = null,
  },
) {
  return list.filter(
    (p) =>
      p.modes.includes(mode) &&
      (category === "Tout" || p.category === category) &&
      (district === "Tout le 7e" || p.district === district) &&
      (!favorites || favorites.includes(p.id)) &&
      normalize(p.name + " " + p.address + " " + p.category).includes(
        normalize(query),
      ),
  );
}
export function chooseIndex(length, random = Math.random) {
  if (!length) throw new Error("Aucun lieu");
  return Math.min(length - 1, Math.floor(random() * length));
}
export function makeWheelPool(list, recent = [], random = Math.random) {
  let pool = list.filter(
    (p) => p.available !== false && !recent.includes(p.id),
  );
  if (!pool.length) pool = list.filter((p) => p.available !== false);
  pool = [...pool];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, 6);
}
export function renewWheelPool(
  list,
  recent = [],
  current = [],
  random = Math.random,
) {
  let eligible = list.filter(
    (p) => p.available !== false && !recent.includes(p.id),
  );
  if (!eligible.length) eligible = list.filter((p) => p.available !== false);
  const old = new Set(current.map((p) => p.id));
  const shuffle = (values) => {
    const result = [...values];
    for (let i = result.length - 1; i > 0; i--) {
      const j = Math.floor(random() * (i + 1));
      [result[i], result[j]] = [result[j], result[i]];
    }
    return result;
  };
  const result = shuffle(
    [
      ...shuffle(eligible.filter((p) => !old.has(p.id))).slice(0, 6),
      ...shuffle(eligible.filter((p) => old.has(p.id))),
    ].slice(0, 6),
  );
  if (result.length > 1 && result.every((p, i) => p.id === current[i]?.id))
    result.push(result.shift());
  return result;
}
export function targetRotation(current, index, count, turns = 6) {
  const tau = Math.PI * 2;
  const target =
    (((Math.PI / 2 - ((index + 0.5) * tau) / count) % tau) + tau) % tau;
  return current + turns * tau + ((target - (current % tau) + tau) % tau);
}
export function spinProgress(p) {
  const a = 0.12,
    k = 4 / (1 + a);
  return p < a
    ? (k * p * p) / (2 * a)
    : k * (a / 2 + ((1 - a) / 4) * (1 - Math.pow((1 - p) / (1 - a), 4)));
}
